/*
  Generates responsive WebP derivatives of everything in img/ into img/opt/
  and writes js/manifest.js (real pixel dimensions, used to prevent layout shift).
  Originals are never modified or deleted.

  Usage (development only, not needed for deployment):
    npm i sharp
    node tools/optimize-images.cjs
*/
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'img');
const OUT = path.join(SRC, 'opt');
const WIDTHS = [720, 1280, 2000];           // upper bounds; never upscaled
const QUALITY = { 720: 80, 1280: 84, 2000: 90, native: 90 };

// store3-1.jpg is a byte-identical PNG copy of art4.png: share one set of derivatives.
const ALIAS = { 'store3-1': 'art4' };

// Cut-outs photographed on solid black: the derivative gets a real alpha channel so the figure
// floats on the site's background instead of sitting in a black box. Only pixels connected to the
// image border and darker than `full` are keyed (alpha ramps from 0 at `solid` up to 1 at `full`),
// so dark detail inside the subject stays opaque. The original file is never modified.
const KNOCK_OUT_BLACK = { shahed: { solid: 4, full: 28 } };

async function knockOutBlack(file, { solid, full }) {
    const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const w = info.width, h = info.height, n = w * h;
    const mx = new Uint8Array(n);
    for (let i = 0; i < n; i += 1) mx[i] = Math.max(data[4 * i], data[4 * i + 1], data[4 * i + 2]);
    const inBg = new Uint8Array(n);
    const stack = [];
    const push = (i) => { if (!inBg[i] && mx[i] <= full) { inBg[i] = 1; stack.push(i); } };
    for (let x = 0; x < w; x += 1) { push(x); push((h - 1) * w + x); }
    for (let y = 0; y < h; y += 1) { push(y * w); push(y * w + w - 1); }
    while (stack.length) {
        const i = stack.pop(), x = i % w, y = (i / w) | 0;
        if (x > 0) push(i - 1);
        if (x < w - 1) push(i + 1);
        if (y > 0) push(i - w);
        if (y < h - 1) push(i + w);
    }
    for (let i = 0; i < n; i += 1) {
        if (inBg[i]) data[4 * i + 3] = Math.round(Math.max(0, Math.min(1, (mx[i] - solid) / (full - solid))) * 255);
    }
    return sharp(data, { raw: { width: w, height: h, channels: 4 } });
}

async function main() {
    fs.mkdirSync(OUT, { recursive: true });
    const files = fs.readdirSync(SRC).filter((f) => /\.(png|jpe?g)$/i.test(f));
    const manifest = {};

    for (const file of files) {
        const name = path.parse(file).name;
        if (name === 'sign') continue;
        if (ALIAS[name]) { manifest[name] = { alias: ALIAS[name] }; continue; }

        const input = sharp(path.join(SRC, file));
        const meta = await input.metadata();
        const stats = await sharp(path.join(SRC, file)).stats();
        const flatten = meta.hasAlpha && stats.isOpaque;

        // Keep a bucket only when it is meaningfully smaller than the native width.
        const widths = WIDTHS.filter((w) => w * 1.2 < meta.width);
        widths.push(Math.min(meta.width, WIDTHS[WIDTHS.length - 1]));

        for (const w of widths) {
            const q = w === meta.width ? QUALITY.native : (QUALITY[w] || 84);
            const keyed = KNOCK_OUT_BLACK[name];
            let p = keyed ? await knockOutBlack(path.join(SRC, file), keyed) : sharp(path.join(SRC, file)).rotate();
            if (flatten && !keyed) p = p.removeAlpha();
            if (w !== meta.width) p = p.resize({ width: w, withoutEnlargement: true });
            await p.webp({ quality: q, alphaQuality: 100, effort: 5 }).toFile(path.join(OUT, `${name}-${w}.webp`));
        }
        manifest[name] = { w: meta.width, h: meta.height, widths };
    }

    // Signature: trim transparent margins, keep alpha.
    const s = sharp(path.join(SRC, 'sign.png'));
    const trimmed = await s.trim().toBuffer({ resolveWithObject: true });
    await sharp(trimmed.data).webp({ quality: 92, alphaQuality: 100, effort: 5 }).toFile(path.join(OUT, `sign-${trimmed.info.width}.webp`));
    manifest.sign = { w: trimmed.info.width, h: trimmed.info.height, widths: [trimmed.info.width] };

    const body = '/* Generated by tools/optimize-images.cjs. Do not edit by hand. */\n' +
        'window.IMAGE_MANIFEST = ' + JSON.stringify(manifest, null, 2) + ';\n';
    fs.writeFileSync(path.join(ROOT, 'js', 'manifest.js'), body);

    let total = 0;
    fs.readdirSync(OUT).forEach((f) => { total += fs.statSync(path.join(OUT, f)).size; });
    console.log(`Wrote ${fs.readdirSync(OUT).length} files, ${(total / 1048576).toFixed(1)} MB total in img/opt/`);
}
main().catch((e) => { console.error(e); process.exit(1); });
